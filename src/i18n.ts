const dictionaries: Record<Language, Record<MessageKey, string>> = { zh, en };
let current: Language = 'zh';

export function setLanguage(language: Language) { current = language; }
export function language() { return current; }
export function resolveLanguage(setting: LanguageSetting, locale: string): Language {
  if (setting !== 'system') return setting;
  return locale.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
export function t(key: MessageKey, params: Record<string, string | number> = {}) {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? ''));
}
export type Message = [MessageKey, Record<string, string | number>?];
export const messageKeys = Object.keys(zh) as MessageKey[];
export function dictionary(language: Language) { return dictionaries[language]; }
